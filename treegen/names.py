"""Every name a species file or a site file may hold: the list treegen/params.py checks a file against.

A name that isn't here is refused when the file loads, with the nearest real names, so a misspelt
setting stops the run instead of growing a tree on the code's fallback.  ``--set`` refuses a name the
loaded values don't hold (treegen/checkpoint.py).

To add a setting: put it in the species file and its full dotted name here, in order.  A name lists a
value; the blocks above it are known from it.  A name is written as nested blocks in a file, never with
a dot in it, except in the one map keyed by dotted names, appearance.provenance (FREE_MAPS): it says
where each look value comes from, so its keys are names of values, not settings.

A list of records (a row per thinning stage, say) has its row names in ROWS: those every row holds,
and those a row may hold.  A name inside a row that isn't there is refused as a setting is.
"""
